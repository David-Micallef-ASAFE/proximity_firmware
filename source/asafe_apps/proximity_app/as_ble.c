/*For now this function has been set to send a standard redlore beacon*/
void asBLEAdvInit()
{
    app_addr_t deviceAddress;
    app_lib_settings_net_addr_t networkAddress;
    int8_t powerDBM = 4;

    // At this point we have not yet allocated a device serial number
    deviceAddress = getUniqueAddress();
    lib_settings->getNetworkAddress(&networkAddress);

    // lib_settings->getNodeAddress(&deviceAddress);
    // lib_settings->getNetworkAddress(&networkAddress);

    LOG(LVL_INFO, "BLE Adv Enabled %u", deviceAddress);

    // Modify random Bluetooth LE beacon address with node address
    //     Encode the device Type
    beacon[BEACON_ADDR_IDX] = ASAFE_DEVICE_TYPE;
    beacon[BEACON_ADDR_IDX + 1] = asProximitySettings.mode == AS_MODE_INVENTORY ? 0 : 1;
    // Encode the device Address
    beacon[BEACON_ADDR_IDX + 2] = (uint8_t)((deviceAddress >> 0) & 0xff);
    beacon[BEACON_ADDR_IDX + 3] = (uint8_t)((deviceAddress >> 8) & 0xff);
    beacon[BEACON_ADDR_IDX + 4] = (uint8_t)((deviceAddress >> 16) & 0xff);
    beacon[BEACON_ADDR_IDX + 5] = (uint8_t)((deviceAddress >> 24) & 0xff);

    beacon[BEACON_INSTANCE_IDX + 2] = (uint8_t)((networkAddress >> 0) & 0xff);
    beacon[BEACON_INSTANCE_IDX + 3] = (uint8_t)((networkAddress >> 8) & 0xff);
    beacon[BEACON_INSTANCE_IDX + 4] = (uint8_t)((networkAddress >> 16) & 0xff);
    beacon[BEACON_INSTANCE_IDX + 5] = (uint8_t)((networkAddress >> 24) & 0xff);

    beacon[BEACON_MEASURED_TX_POWER_IDX] = BEACON_MEASURED_TX_POWER;
    //
    lib_beacon_tx->clearBeacons();
    lib_beacon_tx->setBeaconInterval(300);

    lib_beacon_tx->setBeaconPower(0, &powerDBM);
    lib_beacon_tx->setBeaconChannels(0, APP_LIB_BEACON_TX_CHANNELS_ALL); // All channels
    lib_beacon_tx->setBeaconContents(0, beacon, sizeof(beacon));

    lib_beacon_tx->enableBeacons(true);
}

void asBLEAdvStop()
{
    lib_beacon_tx->enableBeacons(false);
}